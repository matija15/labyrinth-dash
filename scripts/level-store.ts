/** File-backed release level pack: one `<id>.json` per level, `order.json` for the order, and a generated index.ts. */
import fs from 'node:fs';
import path from 'node:path';
import { levelToJson } from '../src/engine/editor';
import { validateLevel } from '../src/engine/world';
import type { LevelDef } from '../src/types';

export const RELEASE_DIR = path.resolve(__dirname, '../src/levels/release');

const ID_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export class StoreError extends Error {
  constructor(public status: number, message: string) {
    super(message);
  }
}

const file = (dir: string, id: string) => path.join(dir, `${id}.json`);

export function readOrder(dir: string): string[] {
  const p = path.join(dir, 'order.json');
  return fs.existsSync(p) ? (JSON.parse(fs.readFileSync(p, 'utf8')) as string[]) : [];
}

export function indexSource(order: string[]): string {
  const head =
    '// Generated by `npm run levels` (scripts/level-server.ts) from order.json. Save levels from the editor instead of editing this.\n' +
    "import type { LevelDef } from '../../types';\n";
  if (!order.length) return `${head}\nexport const RELEASE_LEVELS: LevelDef[] = [];\n`;
  const imports = order.map((id, i) => `import level${i + 1} from './${id}.json';`).join('\n');
  const list = order.map((_, i) => `  level${i + 1},`).join('\n');
  return `${head}${imports}\n\nexport const RELEASE_LEVELS = [\n${list}\n] as unknown as LevelDef[];\n`;
}

function writeOrder(dir: string, order: string[]) {
  fs.writeFileSync(path.join(dir, 'order.json'), JSON.stringify(order, null, 2) + '\n');
  fs.writeFileSync(path.join(dir, 'index.ts'), indexSource(order));
}

export function listLevels(dir: string): LevelDef[] {
  return readOrder(dir).map((id) => JSON.parse(fs.readFileSync(file(dir, id), 'utf8')) as LevelDef);
}

/**
 * Writes a level. `previousId` is the id it was opened under: saving under a new id (renamed) replaces that
 * level in place; a brand-new id is appended to the end of the pack.
 */
export function saveLevel(dir: string, level: LevelDef, previousId?: string | null) {
  if (!level || !Array.isArray(level.rooms) || !level.rooms.length) throw new StoreError(400, 'Not a level');
  if (!ID_RE.test(level.id)) throw new StoreError(400, `Invalid level id "${level.id}"`);
  const order = readOrder(dir);
  const prev = previousId && order.includes(previousId) ? previousId : null;
  if (order.includes(level.id) && prev !== level.id)
    throw new StoreError(409, `A level called "${level.id}" already exists. Give this one another name.`);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(file(dir, level.id), levelToJson(level) + '\n');
  const created = !prev;
  if (prev && prev !== level.id) {
    order[order.indexOf(prev)] = level.id;
    fs.rmSync(file(dir, prev), { force: true });
  } else if (!prev) order.push(level.id);
  writeOrder(dir, order);
  return { position: order.indexOf(level.id) + 1, created, issues: validateLevel(level) };
}

export function deleteLevel(dir: string, id: string) {
  const order = readOrder(dir);
  if (!order.includes(id)) throw new StoreError(404, `No level "${id}"`);
  fs.rmSync(file(dir, id), { force: true });
  writeOrder(dir, order.filter((x) => x !== id));
}

export function reorder(dir: string, ids: string[]) {
  const order = readOrder(dir);
  if (ids.length !== order.length || [...ids].sort().join() !== [...order].sort().join())
    throw new StoreError(400, 'The new order must contain exactly the current levels');
  writeOrder(dir, ids);
}
